"""Rhythmos translations: UI strings, water tips and number formatting (uk, en)."""

LANGUAGES = {"uk": "Українська", "en": "English"}
DEFAULT_LANGUAGE = "uk"

_current = DEFAULT_LANGUAGE


SEP = "  •  "  # the single separator in "name: value  •  name: value" lines (a test keeps it consistent)


def set_language(code):
    global _current
    _current = code if code in LANGUAGES else "en"


def get_language():
    return _current


def t(key, **values):
    text = STRINGS[_current].get(key, STRINGS[DEFAULT_LANGUAGE][key])
    return text.format(**values) if values else text


def content(name):
    return CONTENT[_current][name]


def _plural_uk(n, one, few, many):
    if n % 10 == 1 and n % 100 != 11:
        return one
    return few if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14 else many


def fmt_minutes(v):
    h, m = divmod(v, 60)
    if not h:
        return t("u_min", n=m)
    return t("u_h_min", h=h, m=m) if m else t("u_h", h=h)


def fmt_seconds(v):
    m, s = divmod(v, 60)
    if not m:
        return t("u_sec", n=s)
    return t("u_min_sec", m=m, s=s) if s else t("u_min", n=m)


def fmt_times(v):
    if v == 0:
        return t("times_none")
    if _current == "uk":
        return f"{v} {_plural_uk(v, 'раз', 'рази', 'разів')}"
    return f"{v} {'time' if v == 1 else 'times'}"


def fmt_clock(v):
    """Minutes from midnight → "08:00"; after the workday's midnight (from 24:00) again from "00:00"."""
    v %= 24 * 60
    return f"{v // 60:02d}:{v % 60:02d}"


def fmt_after_minis(v):
    """"Long break after 2 mini breaks"."""
    if _current == "uk":
        return f"після {v} {'міні-перерви' if v % 10 == 1 and v % 100 != 11 else 'міні-перерв'}"
    return f"after {v} mini {'break' if v == 1 else 'breaks'}"


def fmt_days(v):
    if _current == "uk":
        return f"{v} {_plural_uk(v, 'день', 'дні', 'днів')}"
    return f"{v} {'day' if v == 1 else 'days'}"


def fmt_warn(v):
    return t("off") if v == 0 else fmt_seconds(v)


GLASS_LITERS = 0.25  # a standard glass is 250 ml


def fmt_volume(glasses):
    """Approximate water volume: 5 glasses → "≈1,25 л" / "≈1.25 L"."""
    liters = f"{glasses * GLASS_LITERS:g}"
    if _current == "uk":
        return f"≈{liters.replace('.', ',')} л"
    return f"≈{liters} L"


def fmt_glasses(v):
    if _current == "uk":
        return f"{v} {_plural_uk(v, 'склянка', 'склянки', 'склянок')} ({fmt_volume(v)})"
    return f"{v} {'glass' if v == 1 else 'glasses'} ({fmt_volume(v)})"


def fmt_intensity(v):
    return t(f"intensity_{v}")


